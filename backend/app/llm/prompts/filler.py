FILLER_SYSTEM_PROMPT = """\
Вы — автор образовательного контента. Ваша задача — написать содержимое одного блока \
урока на основе его заголовка, типа и контекста.

## Tone of Voice

- Спокойный наставник: честно, практично, без фальшивого восторга и давления.
- Обращение на "вы", гендерно-нейтрально.
- Без стоп-фраз: "Давайте разберёмся!", "Вы когда-нибудь задумывались?", \
"Не правда ли, это интересно?".
- Объясняйте сложное просто, но без снисходительности.
- Используйте конкретные примеры и аналогии из реальной практики.

## Общие правила

- Пишите на русском языке.
- Markdown: используйте заголовки h3 (###) для подразделов внутри блока, \
списки, **жирный** для ключевых терминов, `код` для технических терминов.
- Не повторяйте заголовок секции в тексте.
- Каждый абзац — одна мысль. Не делайте абзацы длиннее 4-5 строк.
"""


def build_markdown_prompt(heading: str, context: str, lesson_title: str) -> str:
    """Build a user prompt for generating a markdown content block."""
    return f"""\
Урок: «{lesson_title}»
Секция: «{heading}»

Контекст (предыдущие блоки урока):
{context if context else "(начало урока)"}

Напишите содержимое этой секции в формате Markdown. \
Объём: 150-300 слов (3-5 содержательных абзацев). \
Используйте примеры, аналогии, структуру (списки, подзаголовки h3 при необходимости). \
Верните ТОЛЬКО текст в формате Markdown, без обёртки в JSON.
"""


def build_quiz_prompt(heading: str, context: str, lesson_title: str) -> str:
    """Build a user prompt for generating a quiz block."""
    return f"""\
Урок: «{lesson_title}»
Секция: «{heading}»

Контекст (предыдущие блоки урока):
{context if context else "(начало урока)"}

Создайте вопрос с выбором одного правильного ответа по материалу этой секции.

Требования:
- 3-4 варианта ответа
- Дистракторы правдоподобные, не очевидно неверные
- Объяснение нейтральное (не "Неправильно!", а "Верный ответ — X, потому что...")
- Вопрос проверяет понимание, а не запоминание формулировки

Верните ТОЛЬКО валидный JSON (без markdown-обёртки):
{{
  "question": "Текст вопроса?",
  "options": [
    {{"id": "a", "text": "Вариант A"}},
    {{"id": "b", "text": "Вариант B"}},
    {{"id": "c", "text": "Вариант C"}},
    {{"id": "d", "text": "Вариант D"}}
  ],
  "correct_option_id": "b",
  "explanation": "Объяснение, почему этот ответ верный."
}}
"""


def build_practice_prompt(heading: str, context: str, lesson_title: str) -> str:
    """Build a user prompt for generating a practice task block."""
    return f"""\
Урок: «{lesson_title}»
Секция: «{heading}»

Контекст (предыдущие блоки урока):
{context if context else "(начало урока)"}

Создайте практическое задание для самостоятельного выполнения.

Требования:
- Описание задачи: конкретное, понятное, выполнимое за 5-10 минут
- 3-5 критериев самопроверки (по ним ученик может сам оценить результат)
- Задание связано с теорией из предыдущих блоков

Если тема урока связана с программированием или JavaScript — добавьте:
- "code_snippet": шаблон кода (функция-заготовка), который ученик должен дописать
- "tests": массив автоматических проверок, каждая — {{"label": "описание", "expression": "JS-выражение, возвращающее true при успехе"}}

Если тема НЕ связана с программированием — верните "code_snippet": null и "tests": null.

Верните ТОЛЬКО валидный JSON (без markdown-обёртки):
{{
  "description": "Подробное описание задания.",
  "criteria": [
    "Критерий 1",
    "Критерий 2",
    "Критерий 3"
  ],
  "code_snippet": "function example(a, b) {{\\n  // ваш код\\n}}" или null,
  "tests": [
    {{"label": "example(1, 2) === 3", "expression": "example(1, 2) === 3"}},
    {{"label": "example(0, 0) === 0", "expression": "example(0, 0) === 0"}}
  ] или null
}}
"""


